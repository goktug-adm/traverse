/** Countries not in the catalog fall back to a stylized generic national monument. */
export function monumentFor(a2, meta) {
  const entry = CATALOG[a2];
  if (entry) return { ...entry, a2, curated: true };
  return {
    a2,
    n: meta?.capital ? `${meta.capital} landmark` : 'National landmark',
    city: meta?.capital || '',
    b: 'monument',
    p: { color: C.marble },
    curated: false
  };
}

